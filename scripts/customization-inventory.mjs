import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ts from 'typescript-compiler';

const root = fileURLToPath(new URL('../', import.meta.url));
const configPath = path.join(root, 'packages/ui/tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configPath));
const program = ts.createProgram(parsed.fileNames, parsed.options);
const checker = program.getTypeChecker();
const manifest = JSON.parse(readFileSync(path.join(root, 'packages/ui/package.json'), 'utf8'));
const entryPaths = [...new Set(Object.values(manifest.exports).map((entry) => `packages/ui/${entry.types.replace(/^\.\//, '')}`))];
const entries = entryPaths.map((name) => program.getSourceFile(path.join(root, name))).filter(Boolean);
const rows = new Map();
const variants = (type) => type.isUnion() ? type.types.flatMap(variants) : [type];
const live = (type) => variants(type).filter((part) => !(part.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null | ts.TypeFlags.Never)));
const propTypes = (type, key) => variants(type).flatMap((part) => {
  const prop = part.getProperty(key);
  return prop ? live(checker.getTypeOfSymbolAtLocation(prop, prop.valueDeclaration ?? prop.declarations[0])) : [];
});
const keys = (types) => [...new Set(types.flatMap((type) => type.getProperties().map((prop) => prop.name)))].sort();
const format = (items) => items.length ? items.map((item) => `\`${item}\``).join(', ') : '—';

function collect(name, type, declaration, family = name) {
  const signature = type.getCallSignatures()[0];
  if (!signature || !signature.parameters[0]) return;
  const props = checker.getTypeOfSymbolAtLocation(signature.parameters[0], declaration);
  const slots = keys(propTypes(props, 'slots'));
  const slotProps = keys(propTypes(props, 'slotProps'));
  const anatomy = keys([props]).filter((key) => /(?:Props|ClassName)$/.test(key) && key !== 'slotProps');
  const component = propTypes(props, 'component').length > 0;
  const parts = type.getProperties().filter((prop) => /^[A-Z]/.test(prop.name));
  rows.set(name, { name, family, component, slots, slotProps, anatomy, parts: parts.map((prop) => prop.name).sort(), source: path.relative(root, declaration.getSourceFile().fileName) });
  for (const part of parts) collect(`${name}.${part.name}`, checker.getTypeOfSymbolAtLocation(part, declaration), declaration, family);
}

for (const entry of entries) {
  for (const exported of checker.getExportsOfModule(checker.getSymbolAtLocation(entry))) {
    if (!/^[A-Z]/.test(exported.name)) continue;
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const declaration = symbol.valueDeclaration;
    if (declaration && declaration.getSourceFile().fileName.includes('/components/')) collect(exported.name, checker.getTypeOfSymbolAtLocation(symbol, declaration), declaration);
  }
}

const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name, 'en'));
const families = sorted.filter((row) => row.name === row.family);
const rootCount = families.filter((row) => row.slots.includes('root')).length;
const interiorCount = families.filter((row) => row.slots.some((key) => key !== 'root')).length;
const stylingOnly = (row) => row.slotProps.filter((key) => !row.slots.includes(key));
const text = `# Customization inventory

Generated by \`node scripts/customization-inventory.mjs\`; verify with \`--check\`.
This table resolves the exported callable components' TypeScript props, including inherited types,
unions and compound parts. A key present in one union branch is listed; mutually exclusive easy and
compound modes still apply. A Panel root seam is listed on the Panel, not credited to its provider.
\`component\` means an accepted replacement prop, not proof of runtime conformance.

## Counts

- Public callable families: **${families.length}**; public callable parts: **${sorted.length - families.length}**.
- Families exposing \`slots.root\`: **${rootCount}**; remaining without a family-level root slot: **${families.length - rootCount}** (includes DOM-less providers).
- Families exposing any non-root replacement slot: **${interiorCount}**; remaining without family-level interior slots: **${families.length - interiorCount}** (includes components without generated anatomy).
- Rows with styling-only \`slotProps\` keys: **${sorted.filter((row) => stylingOnly(row).length).length}**.

Counts describe API exposure, not completed migration or tested adopters. Native dialog shells remain
behavior-owned. GameTable, GameCard, GameHand, FlipGameCard, GameCardStack and CardFlights are owner-held;
their existing APIs are inventoried but not changed. Leaf \`render*\` callbacks are not structural slots.
Public parts are the PascalCase callable properties on the exported component. Separate named exports
also get their own row. Anatomy-prop columns record additional \`*Props\` / \`*ClassName\` customization
props; styling-only keys mean no same-named replacement key on that row (nested part customization
may exist and is listed on the corresponding public part).

## Public APIs

| Component / part | component | slots | slotProps | Styling-only keys | Other anatomy props | Public parts |
| --- | --- | --- | --- | --- | --- | --- |
${sorted.map((row) => `| [${row.name}](../${row.source}) | ${row.component ? 'yes' : '—'} | ${format(row.slots)} | ${format(row.slotProps)} | ${format(stylingOnly(row))} | ${format(row.anatomy)} | ${format(row.parts)} |`).join('\n')}
`;
const target = path.join(root, 'docs/customization-inventory.md');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) throw new Error('Customization inventory is stale. Run node scripts/customization-inventory.mjs.');
} else writeFileSync(target, text);
console.log(`Customization inventory: ${families.length} families, ${rootCount} family roots, ${interiorCount} family interiors, ${sorted.length - families.length} parts.`);

/**
 * Generates `src/catalog.generated.ts` from the library's own story files.
 *
 * This is the "reuse the Storybook definitions" seam: the docs front does not keep a
 * second list of components. It reads each `<component>/<component>.stories.tsx`
 * module's title, exported stories, and whether it has a `component`, and emits a
 * catalog whose `load()` lazily imports the very story module Storybook renders.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)); // apps/docs/scripts
const appDir = join(here, '..'); // apps/docs
const repoRoot = join(appDir, '..', '..');
const componentsDir = join(repoRoot, 'packages', 'ui', 'src', 'components');
const outFile = join(appDir, 'src', 'catalog.generated.ts');

/** Storybook group titles as authored → the docs information architecture. */
const GROUP_ALIASES = {
  Data: 'Data display',
  'Data Display': 'Data display',
};

const GROUP_ORDER = [
  'Getting started',
  'Foundations',
  'Actions',
  'Forms',
  'Inputs',
  'Data display',
  'Feedback',
  'Navigation',
  'Surfaces',
  'Pickers',
  'Layout',
  'Components',
  'Showcase',
];

const kebab = (value) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();

const entries = [];
for (const component of readdirSync(componentsDir)) {
  const storyFile = join(componentsDir, component, `${component}.stories.tsx`);
  let source;
  try {
    source = readFileSync(storyFile, 'utf8');
  } catch {
    continue;
  }
  const titleMatch = source.match(/title:\s*'([^']+)'/) ?? source.match(/title:\s*"([^"]+)"/);
  const title = titleMatch?.[1];
  if (!title) continue;
  const [authoredGroup = 'Components', name = component] = title.split('/');
  const group = GROUP_ALIASES[authoredGroup] ?? authoredGroup;
  const stories = [...source.matchAll(/^export const ([A-Za-z0-9_]+)/gm)].map((m) => m[1]);
  const hasComponent = /component:\s*\w+/.test(source);
  const importPath = relative(join(appDir, 'src'), storyFile).replace(/\\/g, '/');
  entries.push({
    slug: kebab(name),
    name,
    group,
    storybookTitle: title,
    storybookId: kebab(title),
    stories,
    hasComponent,
    importPath,
  });
}

entries.sort((a, b) => {
  const ga = GROUP_ORDER.indexOf(a.group);
  const gb = GROUP_ORDER.indexOf(b.group);
  if (ga !== gb) return (ga === -1 ? 99 : ga) - (gb === -1 ? 99 : gb);
  return a.name.localeCompare(b.name);
});

const groups = [...new Set(entries.map((e) => e.group))].sort((a, b) => {
  const ia = GROUP_ORDER.indexOf(a);
  const ib = GROUP_ORDER.indexOf(b);
  return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
});

const body = entries
  .map(
    (e) =>
      `  { slug: ${JSON.stringify(e.slug)}, name: ${JSON.stringify(e.name)}, group: ${JSON.stringify(e.group)}, ` +
      `storybookTitle: ${JSON.stringify(e.storybookTitle)}, storybookId: ${JSON.stringify(e.storybookId)}, ` +
      `hasComponent: ${e.hasComponent}, stories: ${JSON.stringify(e.stories)}, ` +
      `load: () => import(${JSON.stringify(e.importPath)}) },`,
  )
  .join('\n');

const output = `/* AUTO-GENERATED by scripts/generate-catalog.mjs — run \`pnpm dev\` (or the script) to refresh.
 * Source of truth: the library's own story files (packages/ui/src/components/<name>/<name>.stories.tsx). */

export interface CatalogEntry {
  slug: string;
  name: string;
  group: string;
  storybookTitle: string;
  storybookId: string;
  hasComponent: boolean;
  stories: string[];
  load: () => Promise<Record<string, unknown>>;
}

export const catalog: CatalogEntry[] = [
${body}
];

export const groups: string[] = ${JSON.stringify(groups, null, 0)};

export const stats = { components: ${entries.length}, stories: ${entries.reduce((n, e) => n + e.stories.length, 0)}, groups: ${groups.length} };
`;

writeFileSync(outFile, output);
console.log(
  `catalog: ${entries.length} components, ${entries.reduce((n, e) => n + e.stories.length, 0)} stories, ${groups.length} groups → src/catalog.generated.ts`,
);
